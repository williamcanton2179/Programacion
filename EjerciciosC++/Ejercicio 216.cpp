#include <iostream>
using namespace std;

int main() {
    int a, b;
    cout << "Ingrese dos numeros: ";
    cin >> a >> b;

    cout << "Suma: " << a + b << endl;
    cout << "Producto: " << a * b << endl;
    cout << "Diferencia: " << a - b << endl;
    cout << "Cociente: " << a / b << endl;

    return 0;
}
